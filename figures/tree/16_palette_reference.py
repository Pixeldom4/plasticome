#!/usr/bin/env python3
"""
Step 16: write the fold palette out as a reference.

The palette is defined once, in `15_recolour_atlas.py`. This reads it from
there and writes it in the forms it gets asked for later: a TSV and a JSON to
read from code, a Python module to paste into a drawing script, a swatch sheet
to look at, and a README saying where the hues came from.

Writes ../palette/.
"""

import colorsys
import importlib
import json
import os

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.patches import Rectangle

rc = importlib.import_module("15_recolour_atlas")

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "palette")

FOLD_NAME = {
    "g00": "Alpha/beta hydrolase",
    "g01": "L-amino peptidase D-ALA esterase/amidase",
    "g02": "Amidase signature (AS) domain",
    "g03": "Oxygenase MpaB family protein",
    "g04": "DD-peptidase/beta-lactamase superfamily",
    "g05": "Trypsin-like serine proteases",
    "g06": "Peptidase S8/S53 domain",
    "g07": "Cytochrome c-like domain",
    "g08": "Cupredoxins, blue copper proteins",
    "g09": "SGNH hydrolase",
}
# the lightness and saturation the hand coloured fold labels were given
LABEL_S, LABEL_L = 40.0, 54.0
OTHER = ("#e9e9e6", "Other folds (single sequences)")


def rows():
    out = []
    for g in sorted(rc.FOLD_CATH):
        cath = rc.FOLD_CATH[g]
        hue = rc.ATLAS_HUE.get(cath)
        src = "atlas" if hue is not None else "extended"
        if hue is None:
            hue = rc.EXTRA_HUE[cath]
        tint = rc.hsl_hex(hue, rc.SAT, rc.LIGHT)
        out.append({
            "slice": g,
            "fold": FOLD_NAME[g],
            "catalytic_cath": cath,
            "hue": hue,
            "hue_source": src,
            "tint": tint,
            "tint_second": rc.pie.shade(tint, rc.SECOND_TINT),
            "label": rc.hsl_hex(hue, LABEL_S, LABEL_L),
            "atlas_base": rc.hsl_hex(hue, 60, 38),
        })
    return out


def main():
    os.makedirs(OUT, exist_ok=True)
    data = rows()
    cols = ["slice", "fold", "catalytic_cath", "hue", "hue_source", "tint",
            "tint_second", "label", "atlas_base"]

    with open(os.path.join(OUT, "fold_palette.tsv"), "w") as fh:
        fh.write("\t".join(cols) + "\n")
        for r in data:
            fh.write("\t".join(str(r[c]) for c in cols) + "\n")
    with open(os.path.join(OUT, "fold_palette.json"), "w") as fh:
        json.dump({"folds": data,
                   "other_folds": {"tint": OTHER[0], "fold": OTHER[1]},
                   "construction": {"saturation": rc.SAT, "lightness": rc.LIGHT,
                                    "label_saturation": LABEL_S,
                                    "label_lightness": LABEL_L,
                                    "second_tint_factor": rc.SECOND_TINT}},
                  fh, indent=2)
        fh.write("\n")

    with open(os.path.join(OUT, "fold_palette.py"), "w") as fh:
        fh.write('"""Fold palette, hues from the PETadex atlas. Generated by\n'
                 'tree/16_palette_reference.py, do not edit by hand."""\n\n')
        fh.write("# CATH superfamily -> base hue, as the atlas assigns it\n")
        fh.write("CATH_HUE = {\n")
        for r in data:
            fh.write(f'    "{r["catalytic_cath"]}": {r["hue"]},'
                     f'  # {r["hue_source"]}, {r["slice"]}\n')
        fh.write("}\n\n# slice -> pale slice background, drop in as FOLD_TINT\n")
        fh.write("FOLD_TINT = {\n")
        for r in data:
            fh.write(f'    "{r["catalytic_cath"]}": "{r["tint"]}",'
                     f'  # {r["slice"]} {r["fold"]}\n')
        fh.write("}\n\n")
        fh.write(f'SINGLE_TINT = "{OTHER[0]}"\n\n')
        fh.write("# slice -> colour for a fold label set in the fold's hue\n")
        fh.write("LABEL_COLOUR = {\n")
        for r in data:
            fh.write(f'    "{r["slice"]}": "{r["label"]}",\n')
        fh.write("}\n")

    # --- swatch sheet -------------------------------------------------------
    n = len(data) + 1
    bottom = n - 1.1 - len(data) * 0.52 - 0.45
    fig, ax = plt.subplots(figsize=(9.6, 0.52 * n + 1.05))
    ax.set_xlim(0, 10)
    ax.set_ylim(bottom, n + 0.8)
    ax.axis("off")
    ax.text(0.1, n + 0.35, "Plasticome fold palette", fontsize=12, weight="bold")
    ax.text(4.0, n + 0.37, "hues from petadex.net/atlas (CATH_HUE)",
            fontsize=8, color="#6b6b6b")
    heads = [(0.1, "slice"), (0.75, "CATH"), (2.15, "hue"),
             (2.75, "tint"), (3.75, "2nd"), (4.45, "label"),
             (5.3, "atlas base"), (6.5, "fold")]
    for x, t in heads:
        ax.text(x, n - 0.35, t, fontsize=7.5, color="#6b6b6b")
    for i, r in enumerate(data):
        y = n - 1.1 - i * 0.52
        ax.text(0.1, y + 0.12, r["slice"], fontsize=8.5, weight="bold")
        ax.text(0.75, y + 0.12, r["catalytic_cath"], fontsize=7.5)
        ax.text(2.15, y + 0.12, f'{r["hue"]}',
                fontsize=7.5,
                color="#1a1a1a" if r["hue_source"] == "atlas" else "#9a6a00")
        for x, key in ((2.75, "tint"), (3.75, "tint_second"),
                       (4.45, "label"), (5.3, "atlas_base")):
            ax.add_patch(Rectangle((x, y), 0.62, 0.34, facecolor=r[key],
                                   edgecolor="#b0b0ac", linewidth=0.5))
            ax.text(x, y - 0.11, r[key], fontsize=5.6, color="#6b6b6b")
        ax.text(6.5, y + 0.12, r["fold"][:40], fontsize=7.5)
    y = n - 1.1 - len(data) * 0.52
    ax.add_patch(Rectangle((2.75, y), 0.62, 0.34, facecolor=OTHER[0],
                           edgecolor="#b0b0ac", linewidth=0.5))
    ax.text(2.75, y - 0.11, OTHER[0], fontsize=5.6, color="#6b6b6b")
    ax.text(6.5, y + 0.12, OTHER[1], fontsize=7.5, color="#6b6b6b")
    ax.text(0.1, y + 0.12, "none", fontsize=8.5, color="#6b6b6b")
    fig.subplots_adjust(0, 0, 1, 1)
    for ext in ("svg", "png"):
        fig.savefig(os.path.join(OUT, f"fold_palette.{ext}"),
                    dpi=300, facecolor="#fcfcfb")
    plt.close(fig)

    with open(os.path.join(OUT, "README.md"), "w") as fh:
        fh.write(README.format(
            rows="\n".join(
                f'| {r["slice"]} | {r["fold"]} | `{r["catalytic_cath"]}` | '
                f'{r["hue"]} | {r["hue_source"]} | `{r["tint"]}` | '
                f'`{r["label"]}` | `{r["atlas_base"]}` |' for r in data),
            sat=rc.SAT, light=rc.LIGHT, lab_s=LABEL_S, lab_l=LABEL_L,
            second=rc.SECOND_TINT, other=OTHER[0],
            n_atlas=sum(1 for r in data if r["hue_source"] == "atlas"),
            n_ext=sum(1 for r in data if r["hue_source"] == "extended")))

    print(f"wrote {os.path.normpath(OUT)}/")
    for f in sorted(os.listdir(OUT)):
        print(f"  {f}")


README = """# Plasticome fold palette

One colour per fold of the plasticome tree figure, with the hues taken from the
PETadex atlas so the figure and the site agree on what colour a fold is.

Generated by `tree/16_palette_reference.py`. The definition lives in
`tree/15_recolour_atlas.py`; this folder is output, not source.

## Where the hues come from

The atlas does not store a hex per fold. It stores a **base hue per CATH
superfamily**, in `petadex.io/frontend/src/utils/cathColors.js` as `CATH_HUE`,
and builds every colour it draws from that hue: `HSL(hue, 60, 38)` for the
superfamily and `HSL(hue, 70, 35 to 70)` for the components inside it. Tracking
the atlas therefore means **taking its hue assignment, not its hex values**. The
atlas hexes are tuned for light points on a dark map and would swamp the
substrate coloured tips if dropped in as slice backgrounds.

{n_atlas} of the ten folds have a hue in the atlas. The other {n_ext} CATH
superfamilies are not in the PETadex component set; the atlas would draw them in
its unknown grey, which is no use in a figure where they would then be
indistinguishable from each other and from the "Other folds" slice. They were
given hues in the atlas's own idiom, placed in the widest gaps left by the fixed
six (50 to 140, 140 to 210, 210 to 270, 270 to 360) so the ten stay as far apart
as the fixed assignments allow. They are marked `extended` below and should be
adopted into `CATH_HUE` on the site if the two are to stay in step.

## The palette

| Slice | Fold | CATH | Hue | Source | Tint | Label | Atlas base |
|---|---|---|---:|---|---|---|---|
{rows}

Folds that are a single sequence share `{other}`, as before.

## How each column is built

| Column | Construction | Used for |
|---|---|---|
| `tint` | `HSL(hue, {sat}, {light})` | the slice background. S and L are the means of the ten tints the figure used before, so the figure is no paler or stronger than it was and hue is the only thing that moved |
| `tint_second` | `shade(tint, {second})` | the alternating band that separates neighbouring components inside a slice |
| `label` | `HSL(hue, {lab_s}, {lab_l})` | a fold label set in its own fold's colour. This is the canonical value; the labels in the current figure keep the individual saturation and lightness they were given by hand, with only their hue moved |
| `atlas_base` | `HSL(hue, 60, 38)` | the atlas's own superfamily colour, for anything that sits on a dark background |

The structure cartoons are drawn from `tint` directly, in 26 depth bands between
lightness factors 0.74 and 1.10, with outlines at 0.52 of each band.

## Files

| File | For |
|---|---|
| `fold_palette.tsv` | reading from a script or a spreadsheet |
| `fold_palette.json` | reading from code, with the construction constants |
| `fold_palette.py` | pasting into a drawing script, `FOLD_TINT` drops into `08_draw_pie.py` |
| `fold_palette.svg`, `.png` | looking at |

## One thing to watch

The alpha/beta hydrolase fold takes the atlas's hue 210, which is blue, and its
tips are mostly PET blue. The palette it replaced used a warm tint there
deliberately, for contrast against those tips. The slice is still readable, but
it has less separation from its own tips than it had before. If that matters,
drop the hydrolase tint's saturation rather than moving its hue, so the figure
and the atlas still agree on the hue.
"""


if __name__ == "__main__":
    main()
